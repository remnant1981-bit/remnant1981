def _read(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8")
    except OSError:
        return ""


def load_voice() -> str:
    """voice.md (사용자 문체 프로필) 가 있으면 반환"""
    return _read(BASE_DIR / "voice.md").strip()


def build_system(custom_style: str = "") -> str:
    """시스템 프롬프트. 실행마다 바뀌지 않는 내용만 넣음 (프롬프트 캐시 유지)"""
    parts = [ROLE, KOREAN_STYLE, HONESTY, STRUCTURE, TITLE_RULES, SNS_RULES]
    hooks = _read(VENDOR / "hooks_ko.md")
    if hooks:
        parts.append("## 도입부 훅 패턴 (본문 첫 문장에 하나 골라 사용, 괄호는 실제 내용으로 채움)\n" + hooks)
    voice = load_voice()
    if voice:
        parts.append("## 문체 프로필 (최우선 적용)\n" + voice)
    if custom_style.strip():
        parts.append("## 블로그별 추가 지시\n" + custom_style.strip())
    return "\n\n".join(parts)


