const norm = (s: string) => s.replace(/\s+/g, "").toLowerCase();
const INDEX = new Map<string, { label: string; lat: number; lng: number }>();
for (const [names, lat, lng] of L) { const all = names.split("|"); for (const n of all) INDEX.set(norm(n), { label: all[0], lat, lng }); }

/** 입력과 정확히 같은 이름(공백 무시)의 주요 장소. 없으면 null */
export function findLandmark(text: string): { label: string; lat: number; lng: number } | null {
  return INDEX.get(norm(text)) ?? null;
}
